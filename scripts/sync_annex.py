#!/usr/bin/env python3
"""Read the submission workbook; generate source records without changing Excel."""
import json
from datetime import datetime, date
from pathlib import Path
import openpyxl
ROOT = Path(__file__).resolve().parents[1]
w = openpyxl.load_workbook(ROOT / 'excel/HiLabs_Synthetic_Data_Annex_V2.xlsx', data_only=True)
def value(v):
    if isinstance(v, datetime): return v.strftime('%Y-%m-%d %H:%M')
    if isinstance(v, date): return v.isoformat()
    return '' if v is None else v
records = {}
for sheet in list(w)[3:15]:
    rows=list(sheet.values)
    headers=rows[0]
    for row in rows[1:]:
        if not row[0]: continue
        record={str(k):value(v) for k,v in zip(headers,row) if k is not None}
        record['dataset']=sheet.title
        records[record['record_id']]=record
monday={row[1]:dict(zip([str(x) for x in next(w['8 AM Monday'].values)],map(value,row))) for row in list(w['8 AM Monday'].values)[1:6]}
assert len(records)==75 and len({r['dataset'] for r in records.values()})==12
payload={'snapshot':'2026-11-02T08:00:00-05:00','records':records,'monday':monday}
out=ROOT/'assets/annex-data.js'
out.write_text('// Generated by scripts/sync_annex.py from the unchanged V2 annex.\nwindow.ANNEX_DATA = '+json.dumps(payload,ensure_ascii=False,indent=2).replace('</','<\\/')+';\n')
print(f'Wrote {len(records)} source records across 12 datasets')
